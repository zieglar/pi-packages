/**
 * HANDOFF-853274 — trusted MCP endpoint binding configuration.
 *
 * The MCP server's Endpoint identity comes ONLY from this operator-controlled
 * launch configuration (passed by absolute path on the command line). MCP tool
 * arguments never select a sender, endpoint, participant, session, or
 * capability. This module is a pure validator: it reads no file, no
 * environment, and never echoes configuration values in its errors (only a
 * structural field path).
 */
import { isAbsolute, normalize } from "node:path";
import { LEASE_MAX_TTL_SECONDS, LEASE_MIN_TTL_SECONDS } from "../storage/ownership.js";
import type { CeRecipientRef } from "./endpoint-host.js";

export const MCP_BINDING_CONFIG_VERSION = 1 as const;
export const MCP_DEFAULT_LEASE_TTL_SECONDS = 120;
export const MCP_DEFAULT_RENEW_INTERVAL_SECONDS = 30;
/** Upper bound on the configuration file the composition root will read. */
export const MCP_BINDING_CONFIG_MAX_BYTES = 65_536;

/** HANDOFF-CE-TUNNEL-INTEGRATION-TUI-01: provenance metadata for a CE-managed
 * binding generated by the Tunnel Setup Wizard. It is identity only — never an
 * API key, credential reference, or Store secret — and never grants authority:
 * the endpoint/recipients fields remain the sole message-permission source. */
export interface ManagedBindingMetadata {
  readonly tunnelId: string;
  readonly organizationId?: string;
  readonly adapter: string;
}

export interface McpBindingConfig {
  readonly store: { readonly directory: string; readonly file: string };
  readonly exchange: { readonly namespace: string; readonly idempotencyKey: string };
  readonly endpoint: CeRecipientRef;
  readonly recipients: readonly CeRecipientRef[];
  readonly lease: { readonly ttlSeconds: number; readonly renewIntervalSeconds: number };
  readonly payloadRead: { readonly enabled: boolean };
  /** HANDOFF-CE-E2B-01 operator ACK opt-in; disabled unless explicitly set. */
  readonly ack: { readonly enabled: boolean };
  /** HANDOFF-CE-DIAG-06 development-only execution guard opt-in: when exactly
   * `true`, the MCP server blocks every `tools/call` at the unified dispatch
   * entry (before any business handler) and answers with a fixed JSON-RPC
   * error. Absent means disabled; the production surface is unchanged. */
  readonly debugExecutionGuard: { readonly enabled: boolean };
  /** Optional CE-managed provenance. Absent for operator-authored bindings. */
  readonly managed?: ManagedBindingMetadata;
  /** Operator launch reference for deny-only admission. Never supplies grants. */
  readonly admissionPolicy?: { readonly kind: "ce-multi-session-v1"; readonly profilePath: string };
}

/** Sanitized configuration refusal: a fixed code plus a structural field path;
 * never a configuration value. */
export class McpBindingConfigError extends Error {
  readonly code = "CE_MCP_CONFIG_INVALID" as const;
  readonly field: string;
  constructor(field: string) {
    super(`CE_MCP_CONFIG_INVALID at ${field}`);
    this.name = "McpBindingConfigError";
    this.field = field;
  }
}

const LABEL_MAX = { adapter: 64, endpointId: 256, identity: 256 } as const;
const STORE_FILE_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/;
/** Capability plaintext never belongs in operator configuration. */
const CREDENTIAL_SHAPED = /cap_[0-9a-f]{16,}/i;

function plain(value: unknown, field: string, keys: readonly string[], required: readonly string[]): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) throw new McpBindingConfigError(field);
  const prototype = Object.getPrototypeOf(value);
  if (prototype !== Object.prototype && prototype !== null) throw new McpBindingConfigError(field);
  const own = Reflect.ownKeys(value);
  const out: Record<string, unknown> = {};
  for (const key of own) {
    if (typeof key !== "string" || !keys.includes(key)) throw new McpBindingConfigError(field);
    const descriptor = Object.getOwnPropertyDescriptor(value, key);
    if (descriptor === undefined || !("value" in descriptor) || descriptor.enumerable !== true) {
      throw new McpBindingConfigError(`${field}.${key}`);
    }
    out[key] = descriptor.value;
  }
  for (const key of required) {
    if (!Object.hasOwn(out, key)) throw new McpBindingConfigError(`${field}.${key}`);
  }
  return out;
}

function label(value: unknown, field: string, max: number): string {
  if (typeof value !== "string" || value.length === 0 || value.length > max || value.includes("\u0000")) {
    throw new McpBindingConfigError(field);
  }
  if (CREDENTIAL_SHAPED.test(value)) throw new McpBindingConfigError(field);
  return value;
}

function endpointRef(value: unknown, field: string): CeRecipientRef {
  const fields = plain(value, field, ["adapter", "endpointId"], ["adapter", "endpointId"]);
  return Object.freeze({
    adapter: label(fields.adapter, `${field}.adapter`, LABEL_MAX.adapter),
    endpointId: label(fields.endpointId, `${field}.endpointId`, LABEL_MAX.endpointId),
  });
}

function storeLocation(value: unknown): McpBindingConfig["store"] {
  const fields = plain(value, "store", ["directory", "file"], ["directory"]);
  const directory = fields.directory;
  if (
    typeof directory !== "string" ||
    directory.length === 0 ||
    directory.length > 4096 ||
    directory.includes("\u0000") ||
    !isAbsolute(directory) ||
    normalize(directory) !== directory ||
    directory === "/" ||
    directory.endsWith("/")
  ) {
    throw new McpBindingConfigError("store.directory");
  }
  const file = fields.file === undefined ? "ce-store.sqlite" : fields.file;
  if (typeof file !== "string" || !STORE_FILE_PATTERN.test(file) || file.includes("..")) {
    throw new McpBindingConfigError("store.file");
  }
  return Object.freeze({ directory, file });
}

function integer(value: unknown, field: string, min: number, max: number): number {
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value < min || value > max) {
    throw new McpBindingConfigError(field);
  }
  return value;
}

function leasePolicy(value: unknown): McpBindingConfig["lease"] {
  if (value === undefined) {
    return Object.freeze({ ttlSeconds: MCP_DEFAULT_LEASE_TTL_SECONDS, renewIntervalSeconds: MCP_DEFAULT_RENEW_INTERVAL_SECONDS });
  }
  const fields = plain(value, "lease", ["ttlSeconds", "renewIntervalSeconds"], []);
  const ttlSeconds = fields.ttlSeconds === undefined
    ? MCP_DEFAULT_LEASE_TTL_SECONDS
    : integer(fields.ttlSeconds, "lease.ttlSeconds", LEASE_MIN_TTL_SECONDS, LEASE_MAX_TTL_SECONDS);
  // Renewal must happen at least twice per term so one missed tick cannot
  // let a live process lose its lease.
  const renewIntervalSeconds = fields.renewIntervalSeconds === undefined
    ? Math.min(MCP_DEFAULT_RENEW_INTERVAL_SECONDS, Math.floor(ttlSeconds / 2))
    : integer(fields.renewIntervalSeconds, "lease.renewIntervalSeconds", 1, Math.floor(ttlSeconds / 2));
  return Object.freeze({ ttlSeconds, renewIntervalSeconds });
}

function payloadReadPolicy(value: unknown): McpBindingConfig["payloadRead"] {
  if (value === undefined) return Object.freeze({ enabled: false });
  const fields = plain(value, "payloadRead", ["enabled"], ["enabled"]);
  if (typeof fields.enabled !== "boolean") throw new McpBindingConfigError("payloadRead.enabled");
  return Object.freeze({ enabled: fields.enabled });
}

/** HANDOFF-CE-E2B-01: the ACK opt-in is validated exactly like `payloadRead`.
 * Absent means disabled; only a real boolean is accepted, and an unknown or
 * accessor-backed field refuses with a structural path, never a value. */
function ackPolicy(value: unknown): McpBindingConfig["ack"] {
  if (value === undefined) return Object.freeze({ enabled: false });
  const fields = plain(value, "ack", ["enabled"], ["enabled"]);
  if (typeof fields.enabled !== "boolean") throw new McpBindingConfigError("ack.enabled");
  return Object.freeze({ enabled: fields.enabled });
}

/** HANDOFF-CE-DIAG-06: the development execution guard opt-in is validated
 * exactly like `ack`. Absent means disabled; only a real boolean is accepted,
 * and an unknown or accessor-backed field refuses with a structural path. */
function debugExecutionGuardPolicy(value: unknown): McpBindingConfig["debugExecutionGuard"] {
  if (value === undefined) return Object.freeze({ enabled: false });
  const fields = plain(value, "debugExecutionGuard", ["enabled"], ["enabled"]);
  if (typeof fields.enabled !== "boolean") throw new McpBindingConfigError("debugExecutionGuard.enabled");
  return Object.freeze({ enabled: fields.enabled });
}

const MANAGED_TUNNEL_ID = /^tunnel_[A-Za-z0-9]{8,}$/;
const MANAGED_ORGANIZATION_ID = /^org-[A-Za-z0-9]{1,128}$/;

/** Managed provenance is validated with the same label discipline as every
 * other field: strict identity shapes, no credential-shaped strings. */
function managedMetadata(value: unknown): ManagedBindingMetadata | undefined {
  if (value === undefined) return undefined;
  const fields = plain(value, "managed", ["tunnelId", "organizationId", "adapter"], ["tunnelId", "adapter"]);
  const tunnelId = label(fields.tunnelId, "managed.tunnelId", LABEL_MAX.identity);
  if (!MANAGED_TUNNEL_ID.test(tunnelId)) throw new McpBindingConfigError("managed.tunnelId");
  const adapter = label(fields.adapter, "managed.adapter", LABEL_MAX.adapter);
  const organizationId = fields.organizationId === undefined
    ? undefined
    : label(fields.organizationId, "managed.organizationId", LABEL_MAX.identity);
  if (organizationId !== undefined && !MANAGED_ORGANIZATION_ID.test(organizationId)) {
    throw new McpBindingConfigError("managed.organizationId");
  }
  return Object.freeze({ tunnelId, ...(organizationId === undefined ? {} : { organizationId }), adapter });
}

/** Validate an already-parsed JSON value. Unknown fields, wrong types, unsafe
 * paths, out-of-range lease settings, duplicate or self-referencing
 * recipients, and credential-shaped strings are all refused. */
export function parseMcpBindingConfig(raw: unknown): McpBindingConfig {
  const fields = plain(
    raw,
    "config",
    ["version", "store", "exchange", "endpoint", "recipients", "lease", "payloadRead", "ack", "debugExecutionGuard", "managed", "admissionPolicy"],
    ["version", "store", "exchange", "endpoint", "recipients"],
  );
  if (fields.version !== MCP_BINDING_CONFIG_VERSION) throw new McpBindingConfigError("config.version");
  const store = storeLocation(fields.store);
  const exchangeFields = plain(fields.exchange, "exchange", ["namespace", "idempotencyKey"], ["namespace", "idempotencyKey"]);
  const exchange = Object.freeze({
    namespace: label(exchangeFields.namespace, "exchange.namespace", LABEL_MAX.identity),
    idempotencyKey: label(exchangeFields.idempotencyKey, "exchange.idempotencyKey", LABEL_MAX.identity),
  });
  const managed = fields.managed === undefined ? undefined : managedMetadata(fields.managed);
  let admissionPolicy: McpBindingConfig["admissionPolicy"];
  if (fields.admissionPolicy !== undefined) {
    const ref = plain(fields.admissionPolicy, "admissionPolicy", ["kind", "profilePath"], ["kind", "profilePath"]);
    const path = label(ref.profilePath, "admissionPolicy.profilePath", 4096);
    if (ref.kind !== "ce-multi-session-v1" || !isAbsolute(path) || normalize(path) !== path || /[\u0000-\u001f\u007f]/.test(path)) throw new McpBindingConfigError("admissionPolicy");
    admissionPolicy = Object.freeze({ kind: "ce-multi-session-v1", profilePath: path });
  }
  const endpoint = endpointRef(fields.endpoint, "endpoint");
  if (!Array.isArray(fields.recipients)) throw new McpBindingConfigError("recipients");
  const recipients: CeRecipientRef[] = [];
  const seen = new Set<string>();
  (fields.recipients as unknown[]).forEach((entry, index) => {
    const ref = endpointRef(entry, `recipients[${index}]`);
    if (ref.adapter === endpoint.adapter || ref.endpointId === endpoint.endpointId || seen.has(ref.endpointId)) {
      throw new McpBindingConfigError(`recipients[${index}]`);
    }
    seen.add(ref.endpointId);
    recipients.push(ref);
  });
  return Object.freeze({
    store,
    exchange,
    endpoint,
    recipients: Object.freeze(recipients),
    lease: leasePolicy(fields.lease),
    payloadRead: payloadReadPolicy(fields.payloadRead),
    ack: ackPolicy(fields.ack),
    debugExecutionGuard: debugExecutionGuardPolicy(fields.debugExecutionGuard),
    ...(managed === undefined ? {} : { managed }),
    ...(admissionPolicy === undefined ? {} : { admissionPolicy }),
  });
}
