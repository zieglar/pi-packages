#!/usr/bin/env bash
# Isolated Wayforge Alpha 0 launcher for the project-local Pi 1.x binary.
#
# Everything Pi needs (agent config, session state, and extension loading) is
# redirected below the git-ignored `.wayforge-dev/` directory inside this
# repository. This script never reads or writes the production `~/.pi`
# configuration, never copies credentials, disables Pi telemetry, and skips
# version checks so development is deterministic and offline-safe.
#
# Only two extensions are ever loaded in this isolated profile:
#   1. the Wayforge Alpha 0 extension itself (built from ./dist/extension.js), and
#   2. the project-pinned pi-subagents Worker engine.
#
# Usage:
#   scripts/pi1-dev.sh --setup   install/refresh the isolated extension shims
#   scripts/pi1-dev.sh [pi args...]   run the isolated Pi (auto-setup on first run)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEV_DIR="${REPO_ROOT}/.wayforge-dev"

export PI_CODING_AGENT_DIR="${DEV_DIR}/agent"
export PI_CODING_AGENT_SESSION_DIR="${DEV_DIR}/sessions"
export PI_TELEMETRY="0"
export PI_SKIP_VERSION_CHECK="1"

EXT_DIR="${PI_CODING_AGENT_DIR}/extensions"

install_isolated_extensions() {
  mkdir -p "${PI_CODING_AGENT_DIR}" "${PI_CODING_AGENT_SESSION_DIR}" "${EXT_DIR}"
  # Pi 1.x only discovers extension files ending in .ts or .js (see
  # isExtensionFile in pi-coding-agent/core/extensions/loader.js); .mjs shims
  # are silently skipped. The Alpha 0 dogfood caught this: keep .js names.
  rm -f "${EXT_DIR}/wayforge.mjs" "${EXT_DIR}/pi-subagents.mjs"
  cat > "${EXT_DIR}/wayforge.js" <<EOF
// Generated by scripts/pi1-dev.sh --setup. Isolated Wayforge Alpha 0 entry.
export { wayforgeExtension as default } from "${REPO_ROOT}/dist/extension.js";
EOF
  cat > "${EXT_DIR}/pi-subagents.js" <<'EOF'
// Generated by scripts/pi1-dev.sh --setup. Project-pinned Worker engine shim.
export { default } from "pi-subagents";
EOF
}

case "${1:-}" in
  --setup)
    if [ ! -f "${REPO_ROOT}/dist/extension.js" ]; then
      echo "dist/extension.js is missing; run 'npm run build' before --setup." >&2
      exit 1
    fi
    install_isolated_extensions
    echo "Isolated Wayforge extensions installed under ${EXT_DIR}"
    exit 0
    ;;
esac

if [ ! -f "${EXT_DIR}/wayforge.js" ] || [ ! -f "${EXT_DIR}/pi-subagents.js" ]; then
  if [ ! -f "${REPO_ROOT}/dist/extension.js" ]; then
    echo "dist/extension.js is missing; run 'npm run build' then 'scripts/pi1-dev.sh --setup'." >&2
    exit 1
  fi
  install_isolated_extensions
fi

exec "${REPO_ROOT}/node_modules/.bin/pi" "$@"
